#!/usr/bin/env python3
"""HP 2000F on the VC707, built on the vc707-litex-linux-1gb configuration.

Same generator and flags as the template (VexRiscv-SMP, DDR3 1 GB, ethmin SGMII, SD card), with the HP 2000
machine added as a LiteX module and BIOS commands that replace the Makefile targets (see ../firmware/bios).

    hp2000_vc707.py --cpu-type vexriscv_smp --cpu-variant linux --cpu-count 1 --hardware-breakpoints 0 \\
        --with-wishbone-memory --with-ddr --with-ddr64 --with-ethmin-phy --with-sdcard --l2-size 131072 \\
        --with-led-chaser --flow openXC7 --no-compile-gateware --with-hp2000 --build
"""
import os, sys, shutil

HERE = os.path.dirname(os.path.abspath(__file__))
# The vc707-litex template lives two directories up (examples/vc707-litex); override
# with VC707_LITEX_DIR if it is checked out elsewhere.
TEMPLATE_DIR = os.environ.get("VC707_LITEX_DIR",
    os.path.normpath(os.path.join(HERE, "..", "..", "vc707-litex")))
sys.path.insert(0, TEMPLATE_DIR)
sys.path.insert(0, HERE)

import vc707_litex as base
from hp2000 import HP2000
from litex.soc.integration.builder import Builder


class HP2000SoC(base.BaseSoC):
    def __init__(self, hp_step=12, hp_dram_offset=None, **kwargs):
        with_ddr64 = kwargs.get("with_ddr64", False)
        super().__init__(**kwargs)
        # DDR3 layout: the machine's images sit high, away from BIOS-loaded payloads (low addresses).
        # 128 MB window: disc units at 0, tape at +64 MB (see rtl/dev/hp_disc_store.v, hp_mt.v).
        if hp_dram_offset is None:
            hp_dram_offset = 0x30000000 if with_ddr64 else 0x10000000
        # The eight DIP switches select the boot server (last octet; see firmware/cmd_hp2000.c server_ip()).
        from litex.soc.cores.gpio import GPIOIn
        self.dips = GPIOIn(self.platform.request_all("user_dip_btn"))
        self.hp2000 = HP2000(self.platform, self, dram_offset=hp_dram_offset, step=hp_step)
        self.add_constant("HP2000_DRAM_OFFSET", hp_dram_offset)
        self.add_constant("HP2000_TAPE_OFFSET", 1 << 26)          # bytes: word 2^25
        self.add_constant("HP2000_WINDOW_BASE", 0xa0000000)


def prepare_bios(builder):
    """Build the BIOS from a copy of LiteX's with the HP 2000 commands linked in."""
    import litex
    src = os.path.join(os.path.dirname(litex.__file__), "soc", "software", "bios")
    dst = os.path.join(os.path.dirname(os.path.abspath(builder.output_dir)), "bios-hp2000-src")   # outside the output dir: the builder wipes that
    if os.path.exists(dst):
        shutil.rmtree(dst)
    shutil.copytree(src, dst)
    fw = os.path.join(HERE, "..", "firmware")
    for f in ("cmd_hp2000.c", "taphw.c", "taphw.h"):
        shutil.copy(os.path.join(fw, f), dst)
    # Default boot: the HP 2000 standalone mode (DHCP, TFTP cold boot, telnet terminal lines), never Linux (no netboot of boot.json/boot.bin,
    # no SD/SATA/flash/ROM boot).  The BIOS' own DHCP call is dropped from the network boot method: the standalone mode does it.
    mp = os.path.join(dst, "main.c")
    m = open(mp).read()
    old_dhcp = "#ifdef ETH_WITH_DHCP\n\tdhcp_get_ip();\n#endif\n"
    assert m.count("\tnetboot(0, NULL);") == 1 and old_dhcp in m, "BIOS main.c layout changed"
    m = m.replace(old_dhcp, "").replace("\tnetboot(0, NULL);\n\treturn BOOT_METHOD_CONTINUE;",
                                        "\t{ extern int hp2000_boot_method(void); hp2000_boot_method(); }\n\treturn BOOT_METHOD_CONTINUE;")
    assert "hp2000_boot_method" in m
    m = m.replace("#ifndef CONFIG_BIOS_NO_BOOT\n", "#define FLASH_BOOT_DISABLE\n#define ROM_BOOT_DISABLE\n#define SDCARD_BOOT_DISABLE\n#define SATA_BOOT_DISABLE\n"
                  "#ifndef CONFIG_BIOS_NO_BOOT\n", 1)
    open(mp, "w").write(m)
    import subprocess, sys
    # the 2883 disc boot ROM is our own 47-word program: built into the BIOS as .seg text
    seg = open(os.path.join(HERE, "..", "build", "iss_rom.0.seg")).read()
    with open(os.path.join(dst, "iss_rom.h"), "w") as h:
        h.write("/* generated by litex/hp2000_vc707.py from build/iss_rom.0.seg */\nstatic const char iss_rom_seg[] =\n")
        for line in seg.splitlines():
            h.write('    "%s\\n"\n' % line)
        h.write(";\n")
    # the IOP program: the patched one (BREAK accepted at INPUT prompts, make iop-brk) unless HP_IOP_SEG says otherwise
    iopseg = os.environ.get("HP_IOP_SEG", os.path.join(HERE, "..", "build", "iop_brk.2.seg"))
    runs, addr, cur = [], 0, None
    for tok in open(iopseg).read().split():
        if tok.startswith("@"):
            addr, cur = int(tok[1:], 8), None
            continue
        if cur is None or cur[0] + len(cur[1]) != addr:
            cur = [addr, []]
            runs.append(cur)
        cur[1].append(int(tok, 8))
        addr += 1
    with open(os.path.join(dst, "iop_image.h"), "w") as h:
        h.write("/* generated by litex/hp2000_vc707.py from %s */\n" % os.path.basename(iopseg))
        h.write("static const struct { uint16_t org, n; } iop_runs[] = {\n%s};\n" % "".join("    { %d, %d },\n" % (r[0], len(r[1])) for r in runs))
        words = [w for r in runs for w in r[1]]
        h.write("static const uint16_t iop_words[] = {\n%s};\n" % "".join("    " + ", ".join("%d" % w for w in words[i:i + 12]) + ",\n" for i in range(0, len(words), 12)))
    for f in ("tcpd.c", "tcpd.h"):
        shutil.copy(os.path.join(fw, "telnetd", f), dst)
    liteeth = os.path.join(os.path.dirname(litex.__file__), "soc", "software", "libliteeth", "udp.c")
    subprocess.check_call([sys.executable, os.path.join(fw, "telnetd", "app", "patch_udp.py"), liteeth, os.path.join(dst, "udp.c")])
    mk = os.path.join(dst, "Makefile")
    text = open(mk).read()
    text = text.replace("\t  cmd_bios.o\t\t\\\n", "\t  cmd_bios.o\t\t\\\n\t  cmd_hp2000.o\t\t\\\n\t  taphw.o\t\t\\\n\t  tcpd.o\t\t\\\n\t  udp.o\t\t\\\n", 1)
    text = text.replace("OBJECTS = ", "CFLAGS += -DTCPD_STORAGE=0x41000000UL      # TCP connection table in DDR (the BIOS SRAM is 8 KB)\n\nOBJECTS = ", 1)
    text = text.replace("VPATH = $(BIOS_DIRECTORY):", "VPATH = %s:$(BIOS_DIRECTORY):" % dst, 1)
    open(mk, "w").write(text)
    assert "cmd_hp2000.o" in text, "could not patch the BIOS Makefile"
    builder.software_packages = [(n, d) for n, d in builder.software_packages if n != "bios"]
    builder.add_software_package("bios", src_dir=dst)


def main():
    from litex.build.parser import LiteXArgumentParser
    from litex_boards.platforms import xilinx_vc707
    parser = LiteXArgumentParser(platform=xilinx_vc707.Platform, description="HP 2000F on the VC707.")
    # all of the template's options
    for opt, kw in [
        ("--sys-clk-freq", dict(default=None, type=float)),
        ("--with-led-chaser", dict(action="store_true")), ("--with-ethernet", dict(action="store_true")),
        ("--local-ip", dict(default=base.LOCAL_IP)), ("--remote-ip", dict(default=base.REMOTE_IP)),
        ("--mac-address", dict(default=None, type=lambda v: int(v, 0))),
        ("--with-dhcp", dict(action="store_true")), ("--tftp-port", dict(default=base.TFTP_PORT, type=int)),
        ("--with-ethmin-phy", dict(action="store_true")), ("--with-ddr", dict(action="store_true")),
        ("--sdcard-debug", dict(action="store_true")), ("--with-spi-sdcard", dict(action="store_true")),
        ("--with-sdcard", dict(action="store_true")), ("--with-sdc", dict(action="store_true")),
        ("--with-ddr64", dict(action="store_true")), ("--flow", dict(default="unknown")),
        ("--with-hp2000", dict(action="store_true", help="Add the HP 2000F machine and BIOS commands.")),
        ("--hp-step", dict(default=12, type=int, help="Clock cycles per emulated instruction for device timing.")),
    ]:
        parser.add_target_argument(opt, **kw)
    args = parser.parse_args()

    sys_clk_freq = args.sys_clk_freq or (base.DDR_SYS_CLK_FREQ if args.with_ddr else base.SYS_CLK_FREQ)
    mac = args.mac_address
    if mac is None:
        mac = base.mac_for_cpu(getattr(args, "cpu_type", None), getattr(args, "cpu_variant", None),
                               with_ddr64=args.with_ddr64, cpu_count=getattr(args, "cpu_count", 1))
    kw = dict(sys_clk_freq=sys_clk_freq, with_led_chaser=args.with_led_chaser, with_ddr64=args.with_ddr64,
              with_ethernet=args.with_ethernet, with_ethmin_phy=args.with_ethmin_phy, with_ddr=args.with_ddr,
              with_sdcard=args.with_sdcard, with_sdc=args.with_sdc, with_spi_sdcard=args.with_spi_sdcard,
              sdcard_debug=args.sdcard_debug, local_ip=args.local_ip, remote_ip=args.remote_ip,
              mac_address=mac, tftp_port=args.tftp_port, with_dhcp=args.with_dhcp, flow=args.flow,
              **parser.soc_argdict)
    soc = HP2000SoC(hp_step=args.hp_step, **kw) if args.with_hp2000 else base.BaseSoC(**kw)
    builder = Builder(soc, **parser.builder_argdict)
    if args.with_hp2000:
        prepare_bios(builder)
    if args.build:
        builder.build(**parser.toolchain_argdict)


if __name__ == "__main__":
    main()
