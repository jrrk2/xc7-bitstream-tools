ASMB,A,B,L
      HED ISS DISC ROM BOOTSTRAP (EMULATOR EQUIVALENT OF THE FRONT-PANEL DISC IBL)
*
*  FRONT PANEL PROCEDURE: SET P TO 77750B AND RUN.  READS CYLINDER 0, HEAD 0, SECTOR 0
*  (128 WORDS) OF THE ISS DISC ON SELECT CODES 15B/16B INTO LOCATION 2011B, THEN
*  JUMPS THROUGH 2055B.  THAT SECTOR HOLDS THE TSB PRE-BOOT PROCESSOR WRITTEN BY THE
*  LOADER (SEE "ISS VERSION" IN THE LOADER SOURCE).
*
DAT   EQU 15B       DATA CHANNEL
CMD   EQU 16B       COMMAND CHANNEL
DMAH  EQU 6B
DMAL  EQU 2B
      ORG 77700B
ROM   CLC 0,C       CLEAR ALL CONTROL FLIP-FLOPS
      CLA
      OTA DAT       CYLINDER 0
      STC DAT,C
      LDA SEEK
      JSB CMDO      SEEK COMMAND
      JSB WAITD     CYLINDER ACCEPTED
      CLA
      OTA DAT       HEAD 0, SECTOR 0
      STC DAT,C
      JSB WAITD     HEAD/SECTOR ACCEPTED
      JSB WAITC     SEEK COMPLETE
      LDA DMACW
      OTA DMAH      DMA CONTROL WORD 1
      CLC DMAL
      LDA CORE
      OTA DMAL      INPUT TO 2011B
      STC DMAL
      LDA WCNT
      OTA DMAL      -128 WORDS
      STC DAT,C
      STC DMAH,C
      LDA READ
      JSB CMDO      READ COMMAND
      JSB WAITC     READ COMPLETE
      JMP BSX,I     START THE PRE-BOOT PROCESSOR (ADDRESS IN 2055B)
SEEK  OCT 030000
READ  OCT 040000
DMACW OCT 120015    STC EACH CYCLE, CLC AT END, SELECT CODE 15
CORE  OCT 102011    INPUT, ADDRESS 2011B
WCNT  DEC -128
BSX   DEF 2055B,I
      ORG 77750B
      JMP ROM       FRONT PANEL START ADDRESS
CMDO  NOP
      OTA CMD
      CLC CMD
      STC CMD,C
      JMP CMDO,I
WAITD NOP
      SFS DAT
      JMP *-1
      CLC DAT
      JMP WAITD,I
WAITC NOP
      SFS CMD
      JMP *-1
      JMP WAITC,I
      END
